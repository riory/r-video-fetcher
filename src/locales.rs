pub struct LocaleStrings {
    english: [&'static str; Label::ALL.len()],
    russian: [&'static str; Label::ALL.len()],
}

impl LocaleStrings {
    pub fn load() -> Result<Self> {
        Ok(Self {
            english: parse_locale(include_str!("locales/en.json"))
                .context("Could not load English resources.")?,
            russian: parse_locale(include_str!("locales/ru.json"))
                .context("Could not load Russian resources.")?,
        })
    }

    pub fn text(&self, language: Language, label: Label) -> &'static str {
        match language {
            Language::English => self.english[label as usize],
            Language::Russian => self.russian[label as usize],
        }
    }
}

fn parse_locale(source: &'static str) -> Result<[&'static str; Label::ALL.len()]> {
    let mut resources: HashMap<&'static str, &'static str> =
        serde_json::from_str(source).context("Locale resource JSON is invalid.")?;
    let values = Label::ALL
        .iter()
        .map(|label| {
            resources
                .remove(label.key())
                .ok_or_else(|| anyhow!("Locale resource is missing key '{}'.", label.key()))
        })
        .collect::<Result<Vec<_>>>()?;
    values
        .try_into()
        .map_err(|_| anyhow!("Locale resource count does not match the label table."))
}
